test('uncertain creation asks the admin to inspect results before another write', async ({ page }) => {
  const api = await catalogueAPI(page)
  await page.route('**/api/v1/admin/string-products', route => route.abort('failed'))
  await page.goto('/admin/catalogue')
  await page.getByRole('button', { name: 'Create product', exact: true }).click()
  await productFields(page)
  await page.getByRole('button', { name: 'Save product', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('The save result is uncertain.')
  await expect(page.getByRole('button', { name: 'Save product', exact: true })).toBeDisabled()
  expect(api.writes).toHaveLength(0)
  await page.getByRole('button', { name: 'Back to results', exact: true }).click()
  await expect(page.getByLabel('Search products')).toBeVisible()
})
test('private detail failures and delayed responses cannot become another editor', async ({ page }) => {
  await catalogueAPI(page)
  let release: () => void = () => {}
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route(`**/api/v1/admin/string-products/${catalogueID(1001)}`, async route => { await pending; await route.fulfill({ status: 403, json: { error: { code: 'forbidden', message: 'Administrator permission was revoked.' } } }).catch(() => {}) })
  await page.goto('/admin/catalogue')
  await page.getByRole('button', { name: 'Edit product Preview String 01', exact: true }).click()
  await page.getByRole('button', { name: 'Racket models', exact: true }).click()
  release()
  await expect(page.getByRole('heading', { name: 'Racket models', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Edit string product', exact: true })).toHaveCount(0)
})
