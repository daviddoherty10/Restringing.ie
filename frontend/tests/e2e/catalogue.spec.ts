import { expect, test, type Page } from '@playwright/test'
import { catalogueAPI, catalogueID } from './catalogue-fixture.ts'
async function productFields(page: Page) {
  await page.getByLabel('Brand', { exact: true }).fill('Editorial Preview')
  await page.getByLabel('Model', { exact: true }).fill('New Test String')
  for (const label of ['Comfort', 'Control', 'Power', 'Spin', 'Durability']) await page.getByLabel(label, { exact: true }).fill('3')
}
