test('late inventory responses from a previous business cannot replace the current workspace', async ({ page }) => {
  const api = await dashboardAPI(page)
  let release!: () => void, started!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const reached = new Promise<void>(resolve => { started = resolve })
  await page.route(`**/stringers/${shopID}/manage/inventory?**`, async route => {
    started(); await gate
    await route.fulfill({ json: { data: [{ ...api.variants[0], brand: 'STALE BUSINESS DATA' }], total: 1, page: 1, page_size: 10 } })
  })
  await page.goto('/manage')
  await page.getByRole('button', { name: 'Inventory', exact: true }).click()
  await reached
  await page.getByRole('combobox', { name: 'Your business', exact: true }).selectOption(otherShopID)
  await expect(page.getByRole('heading', { name: 'Preview Racket Room', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Inventory', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Other business string/ })).toBeVisible()
  const finished = page.waitForResponse(r => r.url().includes(`/stringers/${shopID}/manage/inventory`))
  release(); await finished
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => resolve())))
  await expect(page.getByRole('heading', { name: /Other business string/ })).toBeVisible()
  await expect(page.getByText('STALE BUSINESS DATA', { exact: false })).toHaveCount(0)
})
