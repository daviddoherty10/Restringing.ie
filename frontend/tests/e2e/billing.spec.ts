import { expect, test } from '@playwright/test'
import { dashboardAPI, shopID, uid } from './dashboard-fixture.ts'
test('monthly allowance and cash receipt confirmation stay separate from fulfilment', async ({ page }) => {
  const api = await dashboardAPI(page)
  await page.goto('/manage')
  await expect(page.getByText('4 bookings accepted this month · 1 remaining.')).toBeVisible()
  await page.getByRole('button', { name: 'Mark accepted', exact: true }).click()
  await expect(page.getByText(/Monthly allowance reached/)).toBeVisible()
  await page.getByRole('button', { name: 'Record cash received' }).click()
  await expect(page.getByText('Confirm you received €25.99 in cash. This records payment; no online charge is made.')).toBeVisible()
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  expect(api.writes.some(w => w.path.endsWith('/cash-receipt'))).toBe(false)
  await page.getByRole('button', { name: 'Record cash received' }).click()
  await page.getByRole('button', { name: 'Confirm cash received', exact: true }).click()
  await expect(page.getByText('Cash received', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Mark received', exact: true })).toBeVisible()
  expect(api.writes.filter(w => w.path.endsWith('/cash-receipt'))).toHaveLength(1)
  await page.getByRole('button', { name: 'View details' }).click()
  await expect(page.getByText(/Cash receipt confirmed by the stringer/)).toBeVisible()
})
test('owner gets configured billing actions while staff has read-only usage', async ({ page }) => {
  await dashboardAPI(page, 'staff')
  await page.route(`**/api/v1/stringers/${shopID}/billing`, route => route.fulfill({ json: { plan: 'free', accepted_bookings: 5, free_limit: 5, remaining: 0, can_accept: false, resets_at: '2026-11-01T00:00:00Z', subscription_status: 'none', billing_available: true, portal_available: false, monthly_price_cents: 1900 } }))
  await page.goto('/manage')
  await page.getByText('Subscription details', { exact: true }).click()
  await expect(page.getByText('Paid plan: €19.00 per month, tax inclusive. Confirm the recurring charge in secure checkout.')).toBeVisible()
  await expect(page.getByText('Only a business owner or administrator can manage the subscription.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Upgrade to paid' })).toHaveCount(0)
})
test('billing return parameters cannot activate a paid plan and checkout errors are recoverable', async ({ page }) => {
  await dashboardAPI(page)
  await page.route(`**/api/v1/stringers/${shopID}/billing`, route => route.fulfill({ json: { plan: 'free', accepted_bookings: 5, remaining: 0, can_accept: false, resets_at: '2026-11-01T00:00:00Z', subscription_status: 'none', billing_available: true, portal_available: false, monthly_price_cents: 1900 } }))
  await page.route('**/billing/checkout', route => route.fulfill({ status: 503, json: { error: { code: 'billing_unavailable', message: 'Billing is temporarily unavailable.' } } }))
  await page.goto(`/manage?business=${shopID}&billing=success&plan=paid`)
  await expect(page.getByText('Free plan · 5 accepted bookings per month', { exact: true })).toBeVisible()
  await page.getByText('Subscription details', { exact: true }).click()
  await page.getByRole('button', { name: 'Upgrade to paid', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Billing is temporarily unavailable.')
  await expect(page.getByRole('button', { name: 'Upgrade to paid', exact: true })).toBeEnabled()
})
test('public profile keeps a full business visible but disables new bookings', async ({ page }) => {
  await dashboardAPI(page)
  await page.route(`**/api/v1/stringers/${shopID}`, route => route.fulfill({ json: { id: shopID, name: 'Preview at capacity', area: 'Dublin', county: 'Dublin', accepting_orders: true, booking_available: false, approval_status: 'approved', description: 'Fictional listing' } }))
  await page.route(`**/api/v1/stringers/${shopID}/services`, route => route.fulfill({ json: [{ id: uid(4001), active: true, sport: 'tennis', labour_cents: 1500 }] }))
  await page.goto(`/stringers/${shopID}`)
  await expect(page.getByRole('heading', { name: 'Preview at capacity' })).toBeVisible()
  await expect(page.getByText('Currently not accepting bookings', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Choose a setup ↗' })).toHaveCount(0)
})
